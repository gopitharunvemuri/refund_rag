
import json
import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)


class DoclingReader:
    """
    Reads raw JSON files generated by Docling.

    This class does not modify or normalize the
    original Docling document structure.
    """

    def __init__(self, raw_documents_dir: Path):
        self.raw_documents_dir = Path(raw_documents_dir)

        if not self.raw_documents_dir.exists():
            raise FileNotFoundError(
                f"Raw documents directory not found: "
                f"{self.raw_documents_dir}"
            )

        if not self.raw_documents_dir.is_dir():
            raise NotADirectoryError(
                f"Expected a directory: {self.raw_documents_dir}"
            )

    def read_document(self, document_id: str) -> dict[str, Any]:
        """
        Load one Docling JSON document using its document ID.
        """

        file_path = self.raw_documents_dir / f"{document_id}.json"

        if not file_path.exists():
            raise FileNotFoundError(
                f"Docling JSON file not found: {file_path}"
            )

        logger.info("Reading Docling document: %s", document_id)

        try:
            with file_path.open("r", encoding="utf-8") as file:
                document = json.load(file)

        except json.JSONDecodeError as exc:
            raise ValueError(
                f"Invalid JSON in Docling file: {file_path}"
            ) from exc

        if not isinstance(document, dict):
            raise ValueError(
                f"Expected a JSON object in: {file_path}"
            )

        logger.info(
            "Loaded %s: %d text elements, %d tables, %d pages",
            document_id,
            len(document.get("texts", [])),
            len(document.get("tables", [])),
            len(document.get("pages", {})),
        )

        return document


from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent

RAW_DOCUMENTS_DIR = (
    PROJECT_DIR / "parsed_documents" / "raw"
)


def main():
    reader = DoclingReader(RAW_DOCUMENTS_DIR)

    document = reader.read_document(
        "NX-FIN-POL-012"
    )

    print("\nDOCUMENT LOADED SUCCESSFULLY")
    print("----------------------------")

    print("Document name:", document.get("name"))
    print("Schema:", document.get("schema_name"))
    print("Version:", document.get("version"))

    print("Text elements:", len(document.get("texts", [])))
    print("Tables:", len(document.get("tables", [])))
    print("Groups:", len(document.get("groups", [])))
    print("Pages:", len(document.get("pages", {})))

    print("\nFirst body reference:")
    body_children = document.get("body", {}).get("children", [])

    if body_children:
        print(body_children[0])


if __name__ == "__main__":
    main()
